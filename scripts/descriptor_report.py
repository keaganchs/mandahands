"""Descriptors for every valid GENHAND hand and every real hand; normalizer fitted on train; token-level coverage.

  python scripts/descriptor_report.py   # -> registry/descriptor_stats_<dataset>.json, docs/descriptor_report.md (+ png)

Descriptors are cached in data/cache/descriptors/<dataset>.pkl (delete it after changing descriptors.py).
"""

import os
import pickle
import sys
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

os.environ.setdefault("MUJOCO_GL", "egl")

import numpy as np

DATASET = "genhand-1k-v4"
CACHE = Path(f"data/cache/descriptors/{DATASET}.pkl")


def one(hid):
  from mandahands.embodiments import registry

  return hid, registry.descriptor(hid, DATASET)


def main():
  import matplotlib

  matplotlib.use("Agg")
  import matplotlib.pyplot as plt

  from mandahands.embodiments import registry
  from mandahands.embodiments.descriptors import ACT_FIELDS, JOINT_FIELDS, Normalizer, SupportBank

  splits = {s: registry.ids(s, DATASET) for s in ("train", "test_id", "test_ood_topology", "test_ood_scale")}
  real = sorted(p.parent.name for p in Path("data/real_hands").glob("*/hand.xml"))
  if CACHE.exists():
    descs = pickle.loads(CACHE.read_bytes())
  else:
    with ProcessPoolExecutor(os.cpu_count()) as ex:
      descs = dict(ex.map(one, [h for s in splits.values() for h in s] + real, chunksize=4))
    CACHE.parent.mkdir(parents=True, exist_ok=True)
    CACHE.write_bytes(pickle.dumps(descs))

  train = [descs[h] for h in splits["train"]]
  norm = Normalizer.fit(train)
  norm.save(Path("registry") / f"descriptor_stats_{DATASET}.json")
  bank = SupportBank(train, norm)
  p99 = np.percentile(bank.base, 99, 0)

  L = [f"# Descriptor report ({DATASET})", "",
       "Generated by `scripts/descriptor_report.py`. Normalizer fitted on the train split "
       f"({len(train)} hands, {sum(len(d.joint) for d in train)} joint tokens, {sum(len(d.act) for d in train)} actuator tokens); "
       f"statistics in `registry/descriptor_stats_{DATASET}.json`.", "",
       "## Token-level support", "",
       "Score = mean over a hand's tokens of the distance (normalized descriptor space) to the nearest train token of "
       f"another hand. Reference: the same score for each train hand, leave-one-hand-out (joint p99 {p99[0]:.2f}, "
       f"actuator p99 {p99[1]:.2f}). Out of support = above p99 for joints or actuators.", "",
       "| split | hands | out of support | joint score median | actuator score median |", "|---|---|---|---|---|"]
  scores = {}
  for s in ("test_id", "test_ood_topology", "test_ood_scale"):
    sc = [bank.score(descs[h]) for h in splits[s]]
    scores[s] = sc
    L.append(f"| {s} | {len(sc)} | {sum(x['out_of_support'] for x in sc)} ({100 * np.mean([x['out_of_support'] for x in sc]):.0f}%) | "
             f"{np.median([x['joint_nn'] for x in sc]):.2f} | {np.median([x['act_nn'] for x in sc]):.2f} |")
  rs = {h: bank.score(descs[h]) for h in real}
  L.append(f"| real | {len(rs)} | {sum(x['out_of_support'] for x in rs.values())} | "
           f"{np.median([x['joint_nn'] for x in rs.values()]):.2f} | {np.median([x['act_nn'] for x in rs.values()]):.2f} |")
  L += ["", "| real hand | joints | actuators | joint score (pct) | actuator score (pct) | out of support | flags |", "|---|---|---|---|---|---|---|"]
  for h, x in sorted(rs.items(), key=lambda kv: -max(kv[1]["joint_pct"], kv[1]["act_pct"])):
    d = descs[h]
    L.append(f"| {h} | {len(d.joint)} | {len(d.act)} | {x['joint_nn']:.2f} ({x['joint_pct']:.0f}) | {x['act_nn']:.2f} ({x['act_pct']:.0f}) | "
             f"{'**yes**' if x['out_of_support'] else 'no'} | {', '.join(d.flags) or '-'} |")

  # per-field: fraction of real tokens outside the train p1-p99 range (normalized space)
  Zt = np.concatenate([norm.joint(d.joint) for d in train])
  Zr = np.concatenate([norm.joint(descs[h].joint) for h in real])
  At = np.concatenate([norm.act(d.act) for d in train])
  Ar = np.concatenate([norm.act(descs[h].act) for h in real])
  L += ["", "## Per-field coverage of real-hand tokens", "",
        "Share of real tokens outside the train tokens' 1st-99th percentile, per field (fields above 10% listed).", ""]
  for name, fields, t, r in (("joint", JOINT_FIELDS, Zt, Zr), ("actuator", ACT_FIELDS, At, Ar)):
    lo, hi = np.percentile(t, 1, 0), np.percentile(t, 99, 0)
    out = ((r < lo) | (r > hi)).mean(0)
    worst = [f"`{f}` {100 * o:.0f}%" for f, o in sorted(zip(fields, out), key=lambda x: -x[1]) if o > 0.1]
    L.append(f"- {name} tokens ({len(r)} real): {', '.join(worst) or 'none above 10%'}")

  # PCA of joint tokens
  _, _, vt = np.linalg.svd(Zt - Zt.mean(0), full_matrices=False)
  fig, ax = plt.subplots(1, 2, figsize=(13, 6))
  for k, (t, r, title) in enumerate(((Zt, Zr, "joint tokens"), (At, Ar, "actuator tokens"))):
    _, _, v = np.linalg.svd(t - t.mean(0), full_matrices=False)
    ax[k].scatter(*((t - t.mean(0)) @ v[:2].T).T, s=3, c="#bbbbbb", lw=0, label=f"train ({len(t)})")
    ax[k].scatter(*((r - t.mean(0)) @ v[:2].T).T, s=10, c="black", lw=0, label=f"real ({len(r)})")
    ax[k].set(title=f"{title}: PCA of normalized descriptors", xlabel="PC1", ylabel="PC2")
    ax[k].legend(fontsize=8)
  fig.tight_layout()
  fig.savefig("docs/descriptor_tokens.png", dpi=110)
  L += ["", "![tokens](descriptor_tokens.png)", ""]
  Path("docs/descriptor_report.md").write_text("\n".join(L) + "\n")
  print("\n".join(L[:30]))


if __name__ == "__main__":
  sys.exit(main())
