"""Extract every real hand, run the scripted close-and-lift search, write data/real_hands/<id>/ and the report.

  python scripts/extract_real.py              # all hands -> data/real_hands/, docs/real_hands_report.md
  python scripts/extract_real.py talos_right  # some (report is only rewritten for a full run)

Outputs per hand: hand.xml (MJCF, mesh paths are local absolute paths: generated, never redistributed),
meta.json (provenance, joints, actuators, coupling, flags, probe + grasp results), grasp.png (best passing trial).
"""

import json
import os
import sys
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

os.environ.setdefault("MUJOCO_GL", "egl")

OUT = Path("data/real_hands")
REPORT = Path("docs/real_hands_report.md")


def _jsonable(x):
  import numpy as np

  if isinstance(x, dict):
    return {k: _jsonable(v) for k, v in x.items()}
  if isinstance(x, (list, tuple)):
    return [_jsonable(v) for v in x]
  if isinstance(x, np.ndarray):
    return x.tolist()
  if isinstance(x, np.generic):
    return x.item()
  return x


def _to_xml(spec) -> str:
  """spec.to_xml(), with the unnamed nested <default> that attach_body(prefix="") emits given a name.

  MuJoCo writes it but its own parser rejects it ("empty class name"); nothing refers to it by name.
  """
  import xml.etree.ElementTree as ET

  root = ET.fromstring(spec.to_xml())
  for i, d in enumerate(e for top in root.iter("default") for e in top if e.tag == "default" and not e.get("class")):
    d.set("class", f"attached{i}")
  return ET.tostring(root, encoding="unicode")


def run(hid: str) -> dict:
  import mujoco
  import numpy as np
  from PIL import Image

  from mandahands.embodiments.real.extract import extract, git_head
  from mandahands.embodiments.real.sources import HANDS, REPOS
  from mandahands.sim.scripted import close_and_lift, grasp_search

  hs = next(h for h in HANDS if h.id == hid)
  head = git_head(hs.repo)
  if head != REPOS[hs.repo][1]:
    raise RuntimeError(f"{hs.repo} is at {head}, pinned {REPOS[hs.repo][1]}; run scripts/fetch_real.py")
  spec, meta = extract(hs)
  m = spec.copy().compile()
  pr, res = grasp_search(spec, close_override=hs.close)
  ok = [r for r in res if r["ok"]]
  best = min(ok, key=lambda r: r["drift"]) if ok else None

  d = OUT / hid
  d.mkdir(parents=True, exist_ok=True)
  (d / "hand.xml").write_text(_to_xml(spec))
  if best:
    frames = []

    def snap(name, mm, dd):
      if name not in ("open", "held"):
        return
      with mujoco.Renderer(mm, 320, 320) as r:
        cam = mujoco.MjvCamera()
        cam.distance, cam.elevation, cam.lookat[:] = 0.45, -20, dd.mocap_pos[0] - [0, 0, 0.08]
        for az in (30, 120):
          cam.azimuth = az
          r.update_scene(dd, cam)
          frames.append(r.render())

    c = np.asarray(best["centre"])
    cl = next(cl for cc, cl in pr["candidates"] if np.allclose(cc, c))
    close_and_lift(spec, pr, c, cl, best["obj"], on_phase=snap)
    Image.fromarray(np.concatenate([np.concatenate(frames[:2], 1), np.concatenate(frames[2:], 1)], 0)).save(d / "grasp.png")

  meta.update(
    commit_verified=head,
    counts=dict(nbody=m.nbody - 2, njnt=m.njnt, nu=m.nu, neq=m.neq, ntendon=m.ntendon, mass=float(m.body_mass.sum()),
                ncollision=int(((m.geom_contype | m.geom_conaffinity) > 0).sum())),
    probe=dict(ctrl_open=pr["ctrl_open"], ctrl_close=pr["ctrl_close"], close_rule=pr["close_rule"],
               ambiguous=pr["ambiguous"], n_tips=pr["n_tips"], n_candidates=len(pr["candidates"])),
    grasp=dict(passed=len(ok), trials=len(res), best=best, results=res),
  )
  (d / "meta.json").write_text(json.dumps(_jsonable(meta), indent=1))
  return _jsonable(meta)


def report(metas: list[dict]):
  from mandahands.embodiments.real.sources import SKIPPED

  lines = [
    "# Real hands report",
    "",
    "Generated by `scripts/extract_real.py`. Every hand is cut from its source model at a manually chosen root link,",
    "mounted on the floating wrist, and checked with a scripted close-and-lift: object held by a support, hand closes,",
    "support released, wrist lifts 10 cm and holds 0.5 s. Pass = object rose 10 +- 3 cm and moved < 2 cm relative to",
    "the wrist, with the open hand not starting inside it. The search tries sphere/cylinder/box primitives sized to fit",
    "candidate centres found from the hand's open/closed geometry (`mandahands/sim/scripted.py`).",
    "",
    "Assets are generated locally from pinned sources and are not redistributed (CC-BY-SA, LGPL, NASA-1.3 terms).",
    "",
    "| id | robot | license | joints | actuators | coupling | grasp pass | best trial | flags |",
    "|---|---|---|---|---|---|---|---|---|",
  ]
  for m in metas:
    c, g = m["counts"], m["grasp"]
    coup = []
    if m["coupling"]:
      coup.append(f"{len(m['coupling'])} mimic eq")
    if m["tendon_actuators"]:
      coup.append(f"{len(m['tendon_actuators'])} tendon act")
    if c["neq"] > len(m["coupling"]):
      coup.append(f"{c['neq'] - len(m['coupling'])} other eq")
    b = g["best"]
    best = f"{b['obj']} r={1000 * b['size']:.0f} mm, drift {1000 * b['drift']:.0f} mm" if b else "-"
    lines.append(f"| {m['id']} | {m['robot']} | {m['license']} | {c['njnt']} | {c['nu']} | {', '.join(coup) or '-'} | "
                 f"{'PASS' if g['passed'] else 'FAIL'} {g['passed']}/{g['trials']} | {best} | {', '.join(m['flags']) or '-'} |")
  lines += ["", "## Notes per hand", ""]
  for m in metas:
    p = m["provenance"]
    lines.append(f"### {m['id']} ({m['robot']}, {m['source']})")
    lines.append(f"- Source: {p['url']} @ `{p['commit'][:10]}`, `{p['file']}`, root link `{p['hand_root']}`; "
                 f"removed arm joints: {', '.join(m['removed_arm_joints']) or 'none'}")
    lines.append(f"- {m['counts']['njnt']} joints, {m['counts']['nu']} actuators "
                 f"({', '.join(sorted({a['origin'] for a in m['actuators']})) or 'tendon'}), mass {m['counts']['mass']:.3f} kg, "
                 f"{m['counts']['ncollision']} collision geoms")
    rules = m["probe"]["close_rule"]
    lines.append(f"- Closing direction: {sum(v == 'range' for v in rules.values())} by range, "
                 f"{sum(v == 'geometry' for v in rules.values())} by geometry, {sum(v == 'override' for v in rules.values())} override")
    for n in m["notes"]:
      lines.append(f"- {n}")
    lines.append("")
  lines += ["## Inspected and skipped", "", "| model | reason |", "|---|---|"]
  lines += [f"| {k} | {v} |" for k, v in SKIPPED.items()]
  lines += [
    "",
    "## Flag legend",
    "",
    "- `actuators_estimated`: URDF has no actuator model; position servos added (kp = effort / quarter range). Randomize widely.",
    "- `effort_placeholder:N`: URDF effort above 20 Nm (hinge) / 200 N (slide) treated as missing; default 1 Nm / 20 N used.",
    "- `inertia_from_geometry:N`: link inertia was a placeholder (radius of gyration > 10 cm); box estimate from collision geoms.",
    "- `range_placeholder:N`: joint unlimited or wider than 2 pi; actuator command clamped to +-pi/2.",
    "- `collision_approximated:N`: link had no collision geometry (missing meshes); capsules from the kinematic tree.",
    "- `actuator_converted_from_motor`: source torque motor turned into a position servo with the motor's peak torque.",
    "- `convex_decomposed:N`: N collision meshes replaced by CoACD convex parts.",
  ]
  REPORT.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
  from mandahands.embodiments.real.sources import HANDS

  ids = sys.argv[1:] or [h.id for h in HANDS]
  with ProcessPoolExecutor(8) as ex:
    metas = list(ex.map(run, ids))
  for m in metas:
    print(f"{m['id']:24s} {'PASS' if m['grasp']['passed'] else 'FAIL'} {m['grasp']['passed']}/{m['grasp']['trials']}  {m['flags']}")
  if not sys.argv[1:]:
    report(metas)
    print(f"wrote {REPORT}")
